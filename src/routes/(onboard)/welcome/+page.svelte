<script lang="ts">
	import { onMount } from 'svelte';
	import { goto } from '$app/navigation';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import Button from '#lib/ui/Button.svelte';
	import FocusFrame from '#lib/ui/FocusFrame.svelte';
	import Kbd from '#lib/ui/Kbd.svelte';
	import { keys } from '#lib/ui/keys.js';
	import {
		TIMES,
		askPush,
		canNext,
		fromUser,
		initials,
		noChannel,
		pickCustom,
		pickPreset,
		pushBlocked,
		pressed
	} from '#lib/welcome/welcome.js';
	import { saveWelcome } from '#lib/welcome/save.js';
	import { avatarDataUrl } from '#lib/welcome/photo.js';
	import { supabase } from '#lib/supabase.js';
	import { m } from '#lib/paraglide/messages.js';
	import type { PageProps } from './$types';

	let { data }: PageProps = $props();

	// svelte-ignore state_referenced_locally
	let s = $state(fromUser(data.session?.user));
	let picker = $state<HTMLInputElement>();
	let saving = $state(false);
	let asking = $state(false);
	let error = $state('');

	onMount(() => {
		s.pushDenied = pushBlocked(window);
	});

	const none = $derived(s.step === 1 && noChannel(s));
	const next = () => {
		if (canNext(s) && s.step < 2) s.step += 1;
		error = '';
	};
	const back = () => {
		if (s.step > 0) s.step -= 1;
		error = '';
	};

	async function choose(e: Event) {
		const input = e.currentTarget as HTMLInputElement;
		const file = input.files?.[0];
		input.value = '';
		if (!file) return;
		error = '';
		try {
			const photo = await avatarDataUrl(file);
			if (!saving) s.photo = photo;
		} catch {
			error = m.welcome_photo_error();
		}
	}

	async function toggle(key: 'push' | 'emailOn' | 'telegram') {
		if (key !== 'push' || s.push) {
			s[key] = !s[key];
			return;
		}
		if (asking) return;
		asking = true;
		const granted = await askPush(window);
		asking = false;
		s.push = granted;
		s.pushDenied = !granted;
	}

	async function finish(to: '/(app)/(tabs)/today' | '/(onboard)/placement') {
		saving = true;
		error = '';
		try {
			if (!data.session) throw new Error('no session');
			await saveWelcome(s, {
				client: supabase,
				learnerId: data.session.user.id,
				now: new Date(),
				tz: Intl.DateTimeFormat().resolvedOptions().timeZone
			});
		} catch {
			error = m.welcome_save_error();
			saving = false;
			return;
		}
		try {
			await goto(resolve(to));
		} finally {
			saving = false;
		}
	}

	const channels = $derived([
		{
			key: 'push',
			label: m.welcome_push(),
			sub: s.pushDenied ? m.welcome_push_blocked() : m.welcome_push_sub(),
			icon: 'fill-bell'
		},
		{ key: 'emailOn', label: m.welcome_email(), sub: s.email, icon: 'fill-letter' },
		{
			key: 'telegram',
			label: m.welcome_telegram(),
			sub: m.welcome_telegram_sub(),
			icon: 'fill-plain'
		}
	] as const);
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<main use:keys={{ enter: next }}>
	<FocusFrame step={s.step} narrow>
		{#snippet top()}
			<div class="flex items-center gap-3">
				<button
					type="button"
					class="grid size-11 flex-none place-items-center rounded-full text-ink {s.step === 0
						? 'invisible'
						: ''}"
					aria-label={m.welcome_back()}
					tabindex={s.step === 0 ? -1 : 0}
					onclick={back}
				>
					<svg class="size-[22px] rotate-180 fill-current" aria-hidden="true"
						><use href="#i-regular-caret-right" /></svg
					>
				</button>
				<div class="flex flex-1 gap-1.5" aria-hidden="true">
					{#each [0, 1, 2] as i (i)}
						<i class="h-1 flex-1 rounded-full {i <= s.step ? 'bg-ink' : 'bg-ruled-line'}"></i>
					{/each}
				</div>
				<span class="w-10 text-right text-label text-pencil">{s.step + 1}/3</span>
			</div>
		{/snippet}

		{#if s.step === 0}
			<form
				id="step-0"
				onsubmit={(e) => {
					e.preventDefault();
					next();
				}}
			>
				<h2 class="mt-4 text-display">{m.welcome_title()}</h2>
				<p class="mt-2 text-pencil">{m.welcome_profile_lead()}</p>
				<div class="mt-6 grid justify-items-center">
					<div class="relative size-28">
						{#if s.photo}
							<img
								src={s.photo}
								alt=""
								referrerpolicy="no-referrer"
								class="size-full rounded-full object-cover"
							/>
						{:else}
							<span
								class="grid size-full place-items-center rounded-full bg-lantern-red-wash font-display text-[40px] font-semibold text-lantern-red-text"
								>{initials(s.name)}</span
							>
						{/if}
						<button
							type="button"
							class="absolute -right-0.5 -bottom-0.5 grid size-11 place-items-center rounded-full border-[3px] border-notebook-paper bg-ink text-notebook-paper"
							aria-label={m.welcome_photo_change()}
							onclick={() => picker?.click()}
						>
							<svg class="size-5 fill-current" aria-hidden="true"><use href="#i-fill-camera" /></svg
							>
						</button>
						<input
							bind:this={picker}
							type="file"
							accept="image/*"
							class="hidden"
							tabindex="-1"
							onchange={choose}
						/>
					</div>
					{#if s.email}<small
							class="mt-2 max-w-full text-center text-label wrap-anywhere text-pencil"
							>{s.email}</small
						>{/if}
				</div>
				<label class="mt-6 block">
					<span class="text-label font-semibold text-pencil">{m.welcome_name_label()}</span>
					<input
						type="text"
						autocomplete="name"
						maxlength="30"
						bind:value={s.name}
						class="mt-2 h-14 w-full rounded-cell border border-ruled-line bg-white/50 px-4 text-title text-ink"
					/>
				</label>
			</form>
		{:else if s.step === 1}
			<h2 class="mt-4 text-display">{m.welcome_reminder_title()}</h2>
			<p class="mt-2 text-pencil">{m.welcome_reminder_lead()}</p>
			<p class="mt-6 text-label font-semibold text-pencil">{m.welcome_time_label()}</p>
			<div class="mt-2 grid grid-cols-3 gap-2" role="group" aria-label={m.welcome_time_label()}>
				{#each TIMES as [t, label] (t)}
					<button
						type="button"
						aria-pressed={pressed(s).includes(t)}
						class="grid h-16 content-center gap-0.5 rounded-cell border border-ruled-line bg-white/40 hover:not-aria-pressed:bg-white aria-pressed:border-2 aria-pressed:border-ink aria-pressed:bg-white"
						onclick={() => (s = pickPreset(s, t))}
					>
						<b class="font-display text-[19px] font-semibold">{t}</b>
						<small class="text-[12.5px] text-pencil">{label}</small>
					</button>
				{/each}
			</div>
			<label class="mt-3 flex items-center justify-between gap-3">
				<span class="text-label font-semibold text-pencil">{m.welcome_time_other()}</span>
				<input
					type="time"
					value={s.time}
					oninput={(e) => (s = pickCustom(s, e.currentTarget.value))}
					class="h-11 rounded-cell border border-ruled-line bg-white/50 px-3 text-title text-ink"
				/>
			</label>
			<p class="mt-6 text-label font-semibold text-pencil">{m.welcome_channels_label()}</p>
			<ul class="mt-2 border-t border-ruled-line">
				{#each channels as c (c.key)}
					<li
						class="grid grid-cols-[40px_1fr_auto] items-center gap-3 border-b border-ruled-line py-3"
					>
						<span class="grid size-10 place-items-center rounded-cell bg-shaded-paper">
							<svg class="size-[22px] fill-current" aria-hidden="true"
								><use href="#i-{c.icon}" /></svg
							>
						</span>
						<span class="min-w-0">
							<b class="block font-semibold">{c.label}</b>
							<small
								class="block text-label text-pencil {c.key === 'push' && s.pushDenied
									? ''
									: 'truncate'}">{c.sub}</small
							>
						</span>
						<button
							type="button"
							role="switch"
							aria-checked={s[c.key]}
							aria-label={c.label}
							disabled={c.key === 'push' && s.pushDenied}
							class="group grid h-11 w-[52px] place-items-center disabled:opacity-50"
							onclick={() => toggle(c.key)}
						>
							<span
								class="relative block h-8 w-[52px] rounded-full bg-ruled-line transition-colors group-aria-checked:bg-ink motion-reduce:transition-none"
							>
								<span
									class=" absolute top-[3px] left-[3px] size-[26px] rounded-full bg-white transition-transform group-aria-checked:translate-x-5 motion-reduce:transition-none"
								></span>
							</span>
						</button>
					</li>
				{/each}
			</ul>
			<p class="mt-4 text-label text-pencil">{m.welcome_reminder_meta()}</p>
		{:else}
			<div class="mt-4 aspect-[3/2] overflow-hidden rounded-cell">
				<img src="/onboard/start-b0.webp" alt="" class="size-full object-cover" />
			</div>
			<h2 class="mt-4 text-display">{m.welcome_offer_title()}</h2>
			<p class="mt-2 text-pencil">{m.welcome_offer_lead()}</p>
			<ul class="mt-4 grid gap-2 text-ink">
				{#each [m.welcome_offer_1(), m.welcome_offer_2(), m.welcome_offer_3()] as t (t)}
					<li class="grid grid-cols-[22px_1fr] gap-2">
						<svg class="mt-1 size-[18px] fill-current text-lantern-red-text" aria-hidden="true"
							><use href="#i-bold-check" /></svg
						>
						<span>{t}</span>
					</li>
				{/each}
			</ul>
		{/if}

		{#snippet actions()}
			{#if error}
				<p role="alert" class="mb-3 bg-notebook-paper text-center text-label text-lantern-red-text">
					{error}
				</p>
			{/if}
			{#if s.step < 2}
				<Button caret disabled={!canNext(s)} onclick={next}>
					{m.welcome_next()}<Kbd>Enter</Kbd>
				</Button>
				{#if none}
					<p class="mt-3 text-center text-label text-pencil">{m.welcome_no_channel()}</p>
				{/if}
			{:else}
				<Button disabled={saving} onclick={() => finish('/(onboard)/placement')}
					>{m.welcome_offer_cta()}</Button
				>
				<button
					type="button"
					disabled={saving}
					class="mt-3 h-11 w-full text-center text-title text-pencil underline disabled:opacity-50"
					onclick={() => finish('/(app)/(tabs)/today')}
				>
					{m.welcome_skip()}
				</button>
			{/if}
		{/snippet}
	</FocusFrame>
</main>
