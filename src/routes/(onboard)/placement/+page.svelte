<script lang="ts">
	import { goto } from '$app/navigation';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { play, player } from '#lib/audio/index.js';
	import { m } from '#lib/paraglide/messages.js';
	import { answer, HANDOFF, items, startRun } from '#lib/placement/index.js';
	import { shuffle } from '#lib/placement/shuffle.js';
	import Button from '#lib/ui/Button.svelte';
	import FocusFrame from '#lib/ui/FocusFrame.svelte';
	import Kbd from '#lib/ui/Kbd.svelte';
	import { keys } from '#lib/ui/keys.js';
	import Sheet from '#lib/ui/Sheet.svelte';

	let run = $state(startRun(() => crypto.randomUUID()));
	let pick = $state<string | null>(null);
	let leaving = $state(false);
	let shown = 0;

	const item = $derived(items(run.level)[run.index]);
	const options = $derived(shuffle(item.options, Math.random));
	const stepId = $derived(`${run.level}-${run.index}`);

	$effect(() => {
		void stepId;
		pick = null;
		shown = performance.now();
		if (item.kind === 'listen') void play(item.clip);
		return () => player.element()?.pause();
	});

	let playing = $state(false);

	$effect(() => {
		void stepId;
		const el = player.element();
		if (!el) return;
		const on = () => (playing = true);
		const off = () => (playing = false);
		const stops = ['pause', 'ended', 'error', 'emptied', 'abort'];
		playing = !el.paused && !el.ended;
		el.addEventListener('playing', on);
		stops.forEach((name) => el.addEventListener(name, off));
		return () => {
			el.removeEventListener('playing', on);
			stops.forEach((name) => el.removeEventListener(name, off));
			playing = false;
		};
	});

	function submit(chosen: string | null) {
		const at = new Date().toISOString();
		const ms = Math.round(performance.now() - shown);
		const uuid = () => crypto.randomUUID();
		const next = answer(
			run,
			chosen === null
				? { ok: false, ms, at }
				: { ok: chosen === item.answer, pick: chosen, ms, at },
			uuid
		);
		if (!next.done) {
			run = next;
			return;
		}
		sessionStorage.setItem(
			HANDOFF,
			JSON.stringify({ cleared: next.cleared, attempts: next.attempts })
		);
		void goto(resolve('/(onboard)/placement/result'), { replace: true });
	}

	function leave() {
		sessionStorage.removeItem(HANDOFF);
		void goto(resolve('/(app)/(tabs)/today'), { replace: true });
	}

	const handlers = $derived({
		digit: (n: number) => {
			if (n <= 4) pick = options[n - 1];
			else if (n === 5) submit(null);
		},
		enter: () => pick !== null && submit(pick),
		space: item.kind === 'listen' ? () => void play(item.clip) : undefined,
		escape: () => (leaving = true)
	});
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<div class="contents" use:keys={handlers}>
	<FocusFrame step={stepId}>
		{#snippet top()}
			<div class="grid grid-cols-[44px_1fr_44px] items-center">
				<button
					type="button"
					class="relative grid size-11 place-items-center rounded-full"
					aria-label={m.placement_exit_label()}
					onclick={() => (leaving = true)}
				>
					<svg class="size-[22px] fill-current" aria-hidden="true"><use href="#i-regular-x" /></svg>
					<span class="absolute top-[11px] left-[46px]"><Kbd>Esc</Kbd></span>
				</button>
				<span class="text-center font-display text-title">{m.placement_title()}</span>
				<span></span>
			</div>
		{/snippet}

		<p class="mt-5 text-label font-semibold tracking-wider text-lantern-red-text uppercase">
			{item.kind === 'read' ? m.placement_read_eyebrow() : m.placement_listen_eyebrow()}
		</p>
		<h2 class="mt-1 font-display text-headline">
			{item.kind === 'read' ? m.placement_read_title() : m.placement_listen_title()}
		</h2>

		{#if item.kind === 'read'}
			<div
				class="mt-5 border-y border-ruled-line py-6 text-center font-hanzi text-[64px] leading-[1.1] lg:text-[80px]"
			>
				{item.hanzi}
			</div>
		{:else}
			<div class="relative mt-5 grid h-[168px] place-items-center rounded-action bg-shaded-paper">
				<button
					type="button"
					class="speaker"
					class:playing
					aria-label={m.placement_replay()}
					onclick={() => void play(item.clip)}
				>
					<svg class="size-8 fill-current" aria-hidden="true"
						><use href="#i-fill-speaker-high" /></svg
					>
				</button>
				<span class="absolute right-3 bottom-3"><Kbd>Space</Kbd></span>
			</div>
		{/if}

		<div class="mt-5 grid gap-2 {item.kind === 'read' ? 'md:grid-cols-2' : 'grid-cols-2'}">
			{#each options as option, i (option)}
				<button
					type="button"
					class="flex min-h-14 items-center gap-3 rounded-action border px-4 py-3 text-left {item.kind ===
					'listen'
						? 'min-h-[92px] justify-center font-hanzi text-[28px]'
						: ''} {pick === option
						? 'border-2 border-ink bg-white'
						: 'border-ruled-line bg-white/40'}"
					aria-pressed={pick === option}
					onclick={() => (pick = option)}
				>
					<Kbd>{i + 1}</Kbd>
					<span>{option}</span>
				</button>
			{/each}
		</div>

		<button
			type="button"
			class="mt-3 flex min-h-[52px] w-full items-center justify-center gap-2 rounded-action border border-dashed border-faint-pencil font-semibold text-graphite"
			onclick={() => submit(null)}
		>
			{m.placement_unknown()}
			<Kbd>5</Kbd>
		</button>

		{#snippet actions()}
			<Button caret disabled={pick === null} onclick={() => pick !== null && submit(pick)}>
				{m.placement_next()}
				<Kbd>Enter</Kbd>
			</Button>
		{/snippet}
	</FocusFrame>
</div>

<Sheet open={leaving} title={m.placement_exit_title()} onclose={() => (leaving = false)}>
	<p class="mt-2 text-graphite">{m.placement_exit_body()}</p>
	<div class="mt-5 grid gap-3">
		<Button onclick={() => (leaving = false)}>{m.placement_keep()}</Button>
		<Button variant="outline" onclick={leave}>{m.placement_leave()}</Button>
	</div>
</Sheet>

