<script lang="ts">
	import { onMount } from 'svelte';
	import { goto } from '$app/navigation';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { LESSONS } from '#lib/curriculum/index.js';
	import { learnerLedger } from '#lib/learner/index.js';
	import { m } from '#lib/paraglide/messages.js';
	import { readHandoff, recordHandoff } from '#lib/placement/handoff.js';
	import { resultView } from '#lib/placement/result.js';
	import Button from '#lib/ui/Button.svelte';
	import { celebrate } from '#lib/ui/celebrate.js';
	import FocusFrame from '#lib/ui/FocusFrame.svelte';
	import Kbd from '#lib/ui/Kbd.svelte';
	import { keys } from '#lib/ui/keys.js';
	import type { PageProps } from './$types';

	let { data }: PageProps = $props();

	let view = $state<ReturnType<typeof resultView>>();
	let cleared = $state(0);

	const today = () => resolve('/(app)/(tabs)/today');
	const to = $derived(view?.href === '/roadmap' ? resolve('/(app)/(tabs)/roadmap') : today());
	const art = $derived(cleared === 0 ? 'start-b0' : 'placed');

	onMount(() => {
		const handoff = readHandoff(sessionStorage);
		if (!handoff) {
			void goto(today(), { replace: true });
			return;
		}
		cleared = handoff.cleared;
		view = resultView(cleared, LESSONS);

		if (data.session)
			void learnerLedger(data.session)
				.then((ledger) => recordHandoff(sessionStorage, handoff, ledger))
				.catch(() => undefined);

		let stop = () => {};
		const timer = setTimeout(() => {
			if (view && view.confetti !== 'none') stop = celebrate({ big: view.confetti === 'big' });
		}, 250);
		return () => {
			clearTimeout(timer);
			stop();
		};
	});
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<main use:keys={{ enter: () => view && void goto(to), escape: () => void goto(today()) }}>
	<FocusFrame wide step={view?.title}>
		{#snippet top()}
			<div class="grid grid-cols-[44px_1fr_44px] items-center">
				<button
					type="button"
					class="relative grid size-11 cursor-pointer place-items-center rounded-full text-ink"
					aria-label={m.placement_result_exit()}
					onclick={() => void goto(today())}
				>
					<svg class="size-[22px] fill-current" aria-hidden="true"><use href="#i-regular-x" /></svg>
					<span class="absolute top-[11px] left-[46px]"><Kbd>Esc</Kbd></span>
				</button>
				<span class="text-center font-display text-title">{m.placement_result_title()}</span>
				<span></span>
			</div>
		{/snippet}

		{#if view}
			<div class="mt-2 grid gap-5 lg:mt-6 lg:grid-cols-2 lg:items-center lg:gap-14">
				<div class="aspect-3/2 overflow-hidden rounded-[24px] bg-shaded-paper">
					<img
						class="block size-full object-cover"
						src="/onboard/{art}.webp"
						srcset={art === 'placed'
							? '/onboard/placed.webp 860w, /onboard/placed-1280.webp 1280w'
							: undefined}
						sizes="(min-width: 1024px) 480px, (min-width: 768px) 560px, 100vw"
						alt=""
						width="860"
						height="573"
					/>
				</div>
				<div>
					<p class="text-label font-semibold tracking-wider text-lantern-red-text uppercase">
						{view.eyebrow}
					</p>
					<h1 class="mt-1 font-display text-headline lg:text-display">{view.title}</h1>
					<p class="mt-2 text-body text-graphite">{view.lead}</p>
					<dl class="mt-5 border-t border-ruled-line">
						{#each view.rows as row (row.label)}
							<div class="grid grid-cols-[96px_1fr] gap-3 border-b border-ruled-line py-3">
								<dt class="pt-0.5 text-label text-graphite">{row.label}</dt>
								<dd class="leading-snug font-semibold">
									{row.value}
									<span class="block text-label font-normal text-graphite">{row.sub}</span>
								</dd>
							</div>
						{/each}
					</dl>
				</div>
			</div>
		{/if}

		{#snippet actions()}
			{#if view}
				<div class="lg:grid lg:grid-cols-2 lg:gap-14">
					<div class="lg:col-start-2">
						<Button href={to} caret>
							{view.cta}
							<Kbd>Enter</Kbd>
						</Button>
					</div>
				</div>
			{/if}
		{/snippet}
	</FocusFrame>
</main>
