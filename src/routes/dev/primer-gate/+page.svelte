<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import type { LessonContent } from '#lib/catalog/index.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import { toAttempt } from '#lib/lesson/attempt.js';
	import { toAnswer } from '#lib/lesson/choice.js';
	import type { Answer, LessonStep } from '#lib/lesson/index.js';
	import { initialState, type State, type StudyEvent } from '#lib/study/index.js';
	import GateResult from '../../(app)/lesson/[id]/gate/GateResult.svelte';
	import GateRun from '../../(app)/lesson/[id]/gate/GateRun.svelte';
	import type { GateHandoff } from '../../(app)/lesson/[id]/gate/handoff';
	import { primerGate } from '../../(app)/lesson/[id]/gate/primer-gate';
	import { pinyinLookup, resultView, reviewRows } from '../../(app)/lesson/[id]/gate/result';
	import { hubView } from '../../(app)/lesson/[id]/hub';

	const id = 'h0-00';
	const sections = CURRICULUM.lessons.find((l) => l.id === id)?.sections ?? [];
	const seed = Number(page.url.searchParams.get('seed') ?? Date.now());

	const seeded = (n: number) => {
		let a = n;
		return () => {
			a = (a + 0x6d2b79f5) | 0;
			let t = Math.imul(a ^ (a >>> 15), 1 | a);
			t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
			return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
		};
	};

	let lesson = $state<LessonContent>();
	let steps = $state<LessonStep[]>([]);
	let ledger = $state<Ledger>();
	let snapshot = $state<State>(initialState({ curriculum: CURRICULUM }));
	let handoff = $state<GateHandoff>();
	let failed = $state<string>();
	const testOut = $derived(lesson ? hubView(lesson, sections, snapshot).testOut : null);
	const kinds = $derived(
		sections.map((s) => steps.filter((x) => x.id.includes(`-g-${s}-`)).length).join(',')
	);

	onMount(() => {
		let stop = () => {};
		void (async () => {
			try {
				lesson = await catalog.lesson(id);
				steps = primerGate(lesson, seeded(seed));
				const opened = await openLedger({
					initial: initialState({ curriculum: CURRICULUM }),
					store: memoryStore(),
					db: `chaiyo-dev-primer-gate-${seed}-${Date.now()}`
				});
				snapshot = opened.state();
				stop = opened.subscribe((s) => (snapshot = s));
				ledger = opened;
			} catch (e) {
				failed = e instanceof Error ? e.message : String(e);
			}
		})();
		return () => stop();
	});

	async function answer(right: number) {
		if (!lesson || !ledger) return;
		const run = crypto.randomUUID();
		const answers: Answer[] = [];
		const events: StudyEvent[] = [];
		for (const [i, step] of steps.entries()) {
			if (step.kind !== 'choice') continue;
			const a = toAnswer(step, i < right ? step.answer : '', 0);
			answers.push(a);
			events.push(
				...(await ledger.record(
					toAttempt(
						a,
						step.id,
						{ lesson: id, section: 'gate', contentSha: lesson.contentSha, run, of: steps.length },
						{ id: crypto.randomUUID(), at: new Date().toISOString() }
					)
				))
			);
		}
		handoff = {
			lesson: id,
			steps,
			answers,
			events,
			best: ledger.state().lessons[id]?.best ?? 0
		};
	}
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<aside class="m-4 flex flex-col gap-2 text-label text-graphite" data-part="dev-primer-gate">
	<p data-part="testout">test-out link: {testOut?.label ?? 'none'}</p>
	<p data-part="sections">per section ({sections.join(',')}): {kinds}</p>
	<div class="flex gap-2">
		<button data-part="answer-9" disabled={!ledger} class="underline" onclick={() => answer(9)}
			>answer 9/10</button
		>
		<button data-part="answer-7" disabled={!ledger} class="underline" onclick={() => answer(7)}
			>answer 7/10</button
		>
	</div>
	<p>tones:</p>
	<pre data-part="tones">{JSON.stringify(snapshot.tones)}</pre>
	<p>lexicon keys:</p>
	<pre data-part="lexicon">{Object.keys(snapshot.lexicon).length}</pre>
</aside>

{#if failed}
	<p class="p-6" role="alert">failed: {failed}</p>
{:else if lesson && handoff}
	<GateResult
		view={resultView(handoff)}
		rows={reviewRows(handoff.steps, handoff.answers, pinyinLookup(lesson))}
		lesson={id}
		onretry={() => location.reload()}
		onleave={() => {}}
	/>
{:else if lesson && ledger}
	<GateRun
		lesson={id}
		contentSha={lesson.contentSha}
		{steps}
		{ledger}
		ondone={(h) => (handoff = h)}
	/>
{/if}
