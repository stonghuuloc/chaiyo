<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import { memoryStore, openLedger, type Ledger } from '#lib/ledger/index.js';
	import SessionRun from '#lib/practice/SessionRun.svelte';
	import {
		apply,
		initialState,
		session,
		type Attempt,
		type SessionCard,
		type Skill,
		type State
	} from '#lib/study/index.js';

	const SKILLS: Skill[] = ['the', 'nghe', 'viet'];
	const asked = page.url.searchParams.get('skill');
	const only = SKILLS.filter((s) => s === asked);

	let ledger = $state.raw<Ledger>();
	let cards = $state.raw<SessionCard[]>();
	let attempts = $state.raw<Attempt[]>([]);
	let failure = $state('');

	const tracked = (inner: Ledger): Ledger => ({
		...inner,
		record: async (input) => {
			const events = await inner.record(input);
			if (!('kind' in input)) attempts = [...attempts, input];
			return events;
		}
	});

	const seeded = (words: string[]): State => {
		const lanes: [Skill, string[]][] = [
			['the', words.slice(0, 6)],
			['nghe', words.slice(6, 10)],
			['viet', words.slice(10, 12)]
		];
		const at = new Date(Date.now() - 30 * 86_400_000);
		return lanes
			.flatMap(([skill, ws]) => ws.map((word) => ({ word, skill })))
			.reduce(
				(state, { word, skill }) =>
					apply(
						state,
						{
							id: `seed:${skill}:${word}`,
							at: at.toISOString(),
							questionId: `seed:${skill}:${word}`,
							contentSha: 'seed',
							correct: true,
							ms: 1000,
							card: { word, skill }
						},
						at
					).state,
				initialState()
			);
	};

	onMount(() => {
		void (async () => {
			try {
				const content = await catalog.lesson('h1-01');
				const initial = seeded(content.words.map((w) => w.hanzi));
				ledger = tracked(
					await openLedger({
						initial,
						store: memoryStore(),
						db: `chaiyo-dev-practice-session-${crypto.randomUUID()}`
					})
				);
				cards = session(initial, {
					now: new Date(),
					tz: initial.tz,
					only: only.length > 0 ? only : undefined
				});
			} catch (e) {
				failure = String(e);
			}
		})();
	});
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<main class="max-w-sm mx-auto p-4">
	{#if failure}
		<p data-part="failure">{failure}</p>
	{:else if ledger && cards}
		<SessionRun {cards} {ledger} back={resolve('/(app)/(tabs)/practice')} />
	{/if}

	<table class="mt-6 text-label" data-part="attempts">
		<thead><tr><th>questionId</th><th>correct</th><th>of</th></tr></thead>
		<tbody>
			{#each attempts as a (a.id)}
				<tr>
					<td>{a.questionId}</td>
					<td>{String(a.correct)}</td>
					<td>{a.step?.kind === 'practice' ? a.step.of : ''}</td>
				</tr>
			{/each}
		</tbody>
	</table>
</main>
