<script lang="ts">
	import sprite from '#lib/assets/icons.svg?raw';
	import HanziStrokes from '#lib/components/HanziStrokes.svelte';
	import { loadStrokes } from '#lib/components/hanzi-strokes.js';
	import { page } from '$app/state';

	let char = $state(page.url.searchParams.get('c') ?? '你');
	let outline = $state(page.url.searchParams.get('outline') !== '0');
	let progress = $state('none');
	let completes = $state(0);
	let errored = $state(false);
	let loads = $state(0);
	let demo = $state<{ play(): Promise<void> }>();

	const load = (c: string) => {
		loads++;
		return loadStrokes(c);
	};
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}
<main class="max-w-sm mx-auto flex flex-col gap-4 p-4">
	<label>char <input id="char" bind:value={char} class="border border-ruled-line px-2" /></label>
	<label><input id="outline" type="checkbox" bind:checked={outline} /> outline</label>
	<div id="quiz" class="w-[280px]">
		<HanziStrokes
			{char}
			mode="quiz"
			{outline}
			{load}
			onprogress={(p) => (progress = `${p.done}/${p.total} mistakes ${p.mistakes}`)}
			oncomplete={() => completes++}
			onerror={() => (errored = true)}
		/>
	</div>
	<p id="readout">progress {progress} · complete {completes} · error {errored} · loads {loads}</p>
	<div id="animate" class="w-[280px]">
		<HanziStrokes bind:this={demo} char="再" mode="animate" />
	</div>
	<button type="button" id="play" onclick={() => demo?.play()}>play</button>
</main>
