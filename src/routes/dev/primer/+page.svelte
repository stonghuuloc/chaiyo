<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import { catalog } from '#lib/catalog/app.js';
	import type { LessonContent } from '#lib/catalog/index.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import { initialState, type State } from '#lib/study/index.js';
	import Hub from '../../(app)/lesson/[id]/Hub.svelte';
	import PrimerSection from '../../(app)/lesson/[id]/[section]/PrimerSection.svelte';
	import sprite from '#lib/assets/icons.svg?raw';
	import { seedSections } from '../hub/seed';

	const db = 'chaiyo-dev-primer';
	const ids = CURRICULUM.lessons.find((l) => l.id === 'h0-00')?.sections ?? [];
	const section = page.url.searchParams.get('section');

	let lesson = $state<LessonContent>();
	let ledger = $state<Ledger>();
	let study = $state<State>(initialState({ curriculum: CURRICULUM }));
	let failure = $state<string>();
	let resetBlocked = $state(false);

	const erase = (name: string, onBlocked: () => void) => {
		const { promise, resolve, reject } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onblocked = onBlocked;
		req.onerror = () => reject(req.error ?? new Error('delete failed'));
		return promise;
	};

	onMount(() => {
		let off = () => {};
		void (async () => {
			try {
				if (page.url.searchParams.has('reset')) {
					await erase(db, () => (resetBlocked = true));
					location.replace(location.pathname);
					return;
				}
				lesson = await catalog.lesson('h0-00');
				const l = await openLedger({
					initial: initialState({ curriculum: CURRICULUM }),
					store: memoryStore(),
					db
				});
				ledger = l;
				study = l.state();
				off = l.subscribe((next) => (study = next));
			} catch (e) {
				failure = e instanceof Error ? e.message : String(e);
			}
		})();
		return () => off();
	});

	async function seedDone() {
		if (!ledger) return;
		for (const a of seedSections('h0-00', ids, new Date(), () => crypto.randomUUID()))
			await ledger.record(a);
	}
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<div class="m-4 flex flex-wrap gap-4">
	<!-- eslint-disable svelte/no-navigation-without-resolve -- dev-only links keep the query on this page -->
	<a href="?reset" data-sveltekit-reload class="text-label text-graphite underline">reset</a>
	<a href="?" data-sveltekit-reload class="text-label text-graphite underline">hub</a>
	{#each ids as id (id)}
		<a href="?section={id}" data-sveltekit-reload class="text-label text-graphite underline">{id}</a
		>
	{/each}
	<!-- eslint-enable svelte/no-navigation-without-resolve -->
	<button class="rounded-cell border px-3 py-1" onclick={seedDone} disabled={!ledger || !lesson}
		>seed: 5/5 done</button
	>
</div>

{#if resetBlocked && !failure}
	<p class="p-6" role="status">reset waiting: close other tabs on this page</p>
{/if}
{#if failure}
	<p class="p-6" role="alert">{failure}</p>
{:else if lesson && ledger}
	{#if section}
		<PrimerSection {lesson} session={null} ledger={Promise.resolve(ledger)} {section} />
	{:else}
		<Hub {lesson} {study} />
	{/if}
{/if}
