<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import type { LessonContent } from '#lib/catalog/index.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import type { LessonStep } from '#lib/lesson/index.js';
	import { initialState, type State } from '#lib/study/index.js';
	import GateRun from '../../(app)/lesson/[id]/gate/GateRun.svelte';
	import { gateSteps } from '../../(app)/lesson/[id]/gate/gate';
	import { gateSummary } from './summary';

	const db = 'chaiyo-dev-gate';
	const id = 'h1-01';

	let lesson = $state<LessonContent>();
	let steps = $state<LessonStep[]>([]);
	let ledger = $state<Ledger>();
	let snapshot = $state<State>();
	let failed = $state<string>();
	const summary = $derived(snapshot ? gateSummary(snapshot, id) : null);

	const erase = (name: string) => {
		const { promise, resolve, reject } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onerror = () => reject(req.error ?? new Error('delete failed'));
		return promise;
	};

	onMount(() => {
		let stop = () => {};
		void (async () => {
			try {
				if (page.url.searchParams.has('reset')) {
					await erase(db);
					location.replace(location.pathname);
					return;
				}
				lesson = await catalog.lesson(id);
				steps = gateSteps(lesson);
				// testOut lets the gate run score without every section done.
				const curriculum = {
					...CURRICULUM,
					lessons: CURRICULUM.lessons.map((l) => (l.id === id ? { ...l, testOut: true } : l))
				};
				const opened = await openLedger({
					initial: initialState({ curriculum }),
					store: memoryStore(),
					db
				});
				snapshot = opened.state();
				stop = opened.subscribe((s) => (snapshot = s));
				ledger = opened;
			} catch (e) {
				failed = e instanceof Error ? e.message : String(e);
			}
		})();
		return () => stop();
	});
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<aside class="m-4 text-label text-graphite" data-part="dev-gate">
	<!-- eslint-disable svelte/no-navigation-without-resolve -- dev-only links need a full reload; resolve() drops the query -->
	<a href="?reset" data-sveltekit-reload class="underline">reset</a> ·
	<a href="?" data-sveltekit-reload class="underline">new draw</a>
	<!-- eslint-enable svelte/no-navigation-without-resolve -->
	<ol data-part="drawn" class="mt-2 list-decimal pl-5">
		{#each steps as s (s.id)}
			<li>{s.kind} · {s.id}</li>
		{/each}
	</ol>
	{#if summary}
		<p data-part="ledger">
			best: {summary.best ?? '—'} · gate runs: {summary.runs} · open: {summary.open} · last answers:
			{summary.answers}
		</p>
	{/if}
</aside>

{#if failed}
	<p class="p-6" role="alert">failed: {failed}</p>
{:else if lesson && ledger}
	<GateRun lesson={id} contentSha={lesson.contentSha} {steps} {ledger} />
{/if}
