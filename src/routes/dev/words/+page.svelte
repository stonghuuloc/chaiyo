<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import {
		Done,
		StepRunner,
		StreakPopup,
		sectionName,
		type LessonStep
	} from '#lib/lesson/index.js';
	import { m } from '#lib/paraglide/messages.js';
	import { initialState, type StudyEvent } from '#lib/study/index.js';
	import { wordSteps } from '../../(app)/lesson/[id]/[section]/words';

	const db = 'chaiyo-dev-words';

	let events = $state<StudyEvent[] | null>(null);
	let ledger = $state<Ledger>();
	let steps = $state.raw<LessonStep[]>([]);
	let contentSha = $state('');
	let failure = $state('');
	let lexicon = $state<string[]>([]);

	const count = $derived(steps.filter((s) => s.kind === 'word').length);
	const next = { label: m.done_back(), href: resolve('/dev/words') };

	const erase = (name: string) => {
		const { promise, resolve } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onblocked = () => resolve();
		req.onerror = () => resolve();
		return promise;
	};

	onMount(() => {
		let unsubscribe = () => {};
		void (async () => {
			if (page.url.searchParams.has('reset')) {
				await erase(db);
				location.replace(location.pathname);
				return;
			}
			try {
				const content = await catalog.lesson('h1-01');
				contentSha = content.contentSha;
				steps = wordSteps(content);
				const l = await openLedger({
					initial: initialState({ curriculum: CURRICULUM }),
					store: memoryStore(),
					db
				});
				const refresh = () => (lexicon = Object.keys(l.state().lexicon));
				unsubscribe = l.subscribe(refresh);
				refresh();
				ledger = l;
			} catch (e) {
				failure = String(e);
			}
		})();
		return () => unsubscribe();
	});
</script>

<!-- eslint-disable-next-line svelte/no-navigation-without-resolve -- dev-only reset needs a full reload; resolve() drops the query -->
<a href="?reset" data-sveltekit-reload class="m-4 inline-block text-label text-graphite underline"
	>reset</a
>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

{#if failure}
	<p class="p-6" data-part="failure">{failure}</p>
{:else if events}
	<Done
		title={m.done_title({ name: sectionName('words') })}
		text={m.words_done_text({ n: count })}
		{next}
	/>
	<StreakPopup {events} />
{:else if ledger && steps.length > 0}
	<StepRunner
		{steps}
		exit={resolve('/(app)/(tabs)/today')}
		lesson="h1-01"
		section="words"
		{contentSha}
		{ledger}
		onfinish={(e) => (events = e)}
	/>
{/if}

<section class="m-4 text-label" data-part="lexicon">
	<h2>Từ của tôi ({lexicon.length})</h2>
	<p class="font-hanzi">{lexicon.join(' ')}</p>
</section>
