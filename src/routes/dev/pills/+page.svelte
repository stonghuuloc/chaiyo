<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import type { LessonContent } from '#lib/catalog/index.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import { DisplayPrefs } from '#lib/lesson/prefs.svelte.js';
	import { initialState } from '#lib/study/index.js';
	import DialogueSection from '../../(app)/lesson/[id]/[section]/DialogueSection.svelte';
	import GrammarSection from '../../(app)/lesson/[id]/[section]/GrammarSection.svelte';

	const db = 'chaiyo-dev-pills';
	const key = 'chaiyo-prefs-dev';
	const TABS = [
		{ id: 'dialogue', label: 'Hội thoại' },
		{ id: 'grammar', label: 'Ngữ pháp' }
	] as const;

	let lesson = $state<LessonContent>();
	let ledger = $state<Promise<Ledger>>();
	let prefs = $state<DisplayPrefs>();
	let tab = $state<'dialogue' | 'grammar'>('dialogue');
	let failure = $state('');

	const erase = (name: string) => {
		const { promise, resolve } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onblocked = () => resolve();
		req.onerror = () => resolve();
		return promise;
	};

	onMount(() => {
		void (async () => {
			if (page.url.searchParams.has('reset')) {
				localStorage.removeItem(key);
				await erase(db);
				location.replace(location.pathname);
				return;
			}
			try {
				const content = await catalog.lesson(page.url.searchParams.get('lesson') ?? 'h1-01');
				const l = await openLedger({
					initial: initialState({ curriculum: CURRICULUM }),
					store: memoryStore(),
					db
				});
				prefs = new DisplayPrefs({ level: content.lesson.level, key, storage: localStorage });
				ledger = Promise.resolve(l);
				lesson = content;
			} catch (e) {
				failure = String(e);
			}
		})();
	});
</script>

<!-- eslint-disable-next-line svelte/no-navigation-without-resolve -- dev-only reset needs a full reload; resolve() drops the query -->
<a href="?reset" data-sveltekit-reload class="m-4 inline-block text-label text-graphite underline"
	>reset</a
>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

{#if failure}
	<p class="p-6" data-part="failure">{failure}</p>
{:else if lesson && ledger && prefs}
	<div class="m-4 flex gap-2" role="tablist">
		{#each TABS as t (t.id)}
			<button
				type="button"
				role="tab"
				data-part="tab"
				data-tab={t.id}
				aria-selected={tab === t.id}
				class="rounded-pill border px-3 py-1 text-label {tab === t.id
					? 'border-ink'
					: 'border-ruled-line'}"
				onclick={() => (tab = t.id)}
			>
				{t.label}
			</button>
		{/each}
	</div>
	{#key tab}
		{#if tab === 'dialogue'}
			<DialogueSection {lesson} session={null} {ledger} {prefs} />
		{:else}
			<GrammarSection {lesson} session={null} {ledger} {prefs} />
		{/if}
	{/key}
	<pre class="m-4 text-label" data-part="prefs">{JSON.stringify(prefs.stored)}</pre>
{/if}
