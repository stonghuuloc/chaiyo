<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { all, open } from '#lib/ledger/idb.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import { StepRunner, type LessonStep } from '#lib/lesson/index.js';
	import { initialState } from '#lib/study/index.js';
	import { listenSpeakSteps } from '../../(app)/lesson/[id]/[section]/listen-speak';
	import { attemptLines } from './attempts';

	const db = 'chaiyo-dev-listen';

	let finished = $state(false);
	let ledger = $state<Ledger>();
	let steps = $state<LessonStep[]>([]);
	let contentSha = $state('');
	let failure = $state('');
	let lines = $state<ReturnType<typeof attemptLines>>([]);

	const erase = (name: string) => {
		const { promise, resolve } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onblocked = () => resolve();
		req.onerror = () => resolve();
		return promise;
	};

	const refresh = async () => {
		const handle = await open(indexedDB, db);
		lines = attemptLines(await all(handle));
		handle.close();
	};

	onMount(() => {
		let unsubscribe = () => {};
		void (async () => {
			if (page.url.searchParams.has('reset')) {
				await erase(db);
				location.replace(location.pathname);
				return;
			}
			try {
				const content = await catalog.lesson('h1-01');
				contentSha = content.contentSha;
				steps = listenSpeakSteps(content);
				const l = await openLedger({
					initial: initialState({ curriculum: CURRICULUM }),
					store: memoryStore(),
					db
				});
				unsubscribe = l.subscribe(() => void refresh());
				ledger = l;
				await refresh();
			} catch (e) {
				failure = String(e);
			}
		})();
		return () => unsubscribe();
	});
</script>

<!-- eslint-disable-next-line svelte/no-navigation-without-resolve -- dev-only reset needs a full reload; resolve() drops the query -->
<a href="?reset" data-sveltekit-reload class="m-4 inline-block text-label text-graphite underline"
	>reset</a
>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

{#if failure}
	<p class="p-6" data-part="failure">{failure}</p>
{:else if finished}
	<p class="p-6">finished</p>
{:else if ledger && steps.length > 0}
	<StepRunner
		{steps}
		exit={resolve('/(app)/(tabs)/today')}
		lesson="h1-01"
		section="listenSpeak"
		{contentSha}
		{ledger}
		onfinish={() => (finished = true)}
	/>
{/if}

<table class="m-4 text-label" data-part="attempts">
	<thead><tr><th>step</th><th>pick</th><th>correct</th></tr></thead>
	<tbody>
		{#each lines as line (line.id)}
			<tr><td>{line.step}</td><td>{line.pick ?? '–'}</td><td>{String(line.correct)}</td></tr>
		{/each}
	</tbody>
</table>
