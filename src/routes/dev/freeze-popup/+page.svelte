<script lang="ts">
	import sprite from '#lib/assets/icons.svg?raw';
	import { FreezePopup, StreakPopup, type FreezeUsedView } from '#lib/lesson/index.js';
	import type { StudyEvent } from '#lib/study/index.js';
	import { SCENARIOS } from './scenarios';

	let freeze = $state<FreezeUsedView | null>(null);
	let events = $state<StudyEvent[] | null>(null);
	let run = $state(0);

	const pick = (name: keyof typeof SCENARIOS) => {
		const built = SCENARIOS[name]();
		events = Array.isArray(built) ? built : null;
		freeze = Array.isArray(built) ? null : built;
		run += 1;
	};
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<div class="m-4 flex gap-4">
	{#each Object.keys(SCENARIOS) as name (name)}
		<button
			class="rounded-cell border px-3 py-1"
			data-part="scenario"
			onclick={() => pick(name as keyof typeof SCENARIOS)}>{name}</button
		>
	{/each}
</div>
<p class="m-4 text-muted">
	Toggle DevTools, Rendering, Emulate CSS prefers-reduced-motion, then pick a scenario again.
</p>

{#key run}
	{#if freeze}
		<FreezePopup view={freeze} />
	{:else if events}
		<StreakPopup {events} />
	{/if}
{/key}
