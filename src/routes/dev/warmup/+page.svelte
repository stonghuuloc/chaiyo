<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import type { LessonContent } from '#lib/catalog/index.js';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import {
		Done,
		StepRunner,
		StreakPopup,
		sectionName,
		type LessonStep
	} from '#lib/lesson/index.js';
	import { m } from '#lib/paraglide/messages.js';
	import { initialState, type StudyEvent } from '#lib/study/index.js';
	import { warmupScore, warmupSteps, warmupWords } from '../../(app)/lesson/[id]/[section]/warmup';

	const db = 'chaiyo-dev-warmup';
	const open = 'h1-02';

	let events = $state<StudyEvent[] | null>(null);
	let ledger = $state<Ledger>();
	let prev = $state.raw<LessonContent>();
	let steps = $state.raw<LessonStep[]>([]);
	let before = new Set<string>();
	let right = $state(0);
	let failure = $state('');
	let due = $state<string[]>([]);

	const next = { label: m.done_back(), href: resolve('/dev/warmup') };

	const erase = (name: string) => {
		const { promise, resolve } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onblocked = () => resolve();
		req.onerror = () => resolve();
		return promise;
	};

	const plan = (l: Ledger, content: LessonContent) => {
		const state = l.state();
		before = new Set(
			Object.entries(state.runs)
				.filter(([, r]) => r.closed)
				.map(([run]) => run)
		);
		steps = warmupSteps(content, warmupWords(state, open, new Date(), state.tz));
	};

	const seed = async () => {
		if (!ledger || !prev) return;
		for (const word of CURRICULUM.lessons.find((l) => l.id === 'h1-01')?.words ?? [])
			await ledger.record({
				id: crypto.randomUUID(),
				at: new Date().toISOString(),
				questionId: `seed-${word}`,
				contentSha: prev.contentSha,
				correct: true,
				ms: 1,
				card: { word, skill: 'the' }
			});
		plan(ledger, prev);
	};

	onMount(() => {
		let unsubscribe = () => {};
		void (async () => {
			if (page.url.searchParams.has('reset')) {
				await erase(db);
				location.replace(location.pathname);
				return;
			}
			try {
				const content = await catalog.lesson('h1-01');
				prev = content;
				const l = await openLedger({
					initial: initialState({ curriculum: CURRICULUM }),
					store: memoryStore(),
					db
				});
				const refresh = () =>
					(due = Object.entries(l.state().lexicon).map(
						([word, e]) => `${word} the ${e.cards.the?.due ?? '-'} nghe ${e.cards.nghe?.due ?? '-'}`
					));
				unsubscribe = l.subscribe(refresh);
				refresh();
				plan(l, content);
				ledger = l;
			} catch (e) {
				failure = String(e);
			}
		})();
		return () => unsubscribe();
	});
</script>

<!-- eslint-disable-next-line svelte/no-navigation-without-resolve -- dev-only reset needs a full reload; resolve() drops the query -->
<a href="?reset" data-sveltekit-reload class="m-4 inline-block text-label text-graphite underline"
	>reset</a
>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

{#if failure}
	<p class="p-6" data-part="failure">{failure}</p>
{:else if events}
	<Done
		title={m.done_title({ name: sectionName('warmup') })}
		text={right < 6
			? m.warmup_done_miss({ k: right, total: 6 })
			: m.warmup_done_all({ k: right, total: 6 })}
		{next}
	/>
	<StreakPopup {events} />
{:else if ledger && prev && steps.length > 0}
	<StepRunner
		{steps}
		exit={resolve('/(app)/(tabs)/today')}
		lesson={open}
		section="warmup"
		contentSha={prev.contentSha}
		{ledger}
		onfinish={(e) => {
			right = warmupScore(before, ledger!.state(), open);
			events = e;
		}}
	/>
{:else if ledger}
	<button type="button" data-part="seed" class="m-4 underline" onclick={seed}>seed Bài 1</button>
{/if}

<section class="m-4 text-label" data-part="lexicon">
	<h2>Từ của tôi ({due.length})</h2>
	<ul class="font-hanzi">
		{#each due as line (line)}
			<li>{line}</li>
		{/each}
	</ul>
</section>
