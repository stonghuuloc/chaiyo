<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import { resolve } from '$app/paths';
	import sprite from '#lib/assets/icons.svg?raw';
	import { CURRICULUM } from '#lib/curriculum/index.js';
	import { openLedger, memoryStore, type Ledger } from '#lib/ledger/index.js';
	import { doneNext } from '#lib/lesson/index.js';
	import WritingRun from '#lib/lesson/WritingRun.svelte';
	import { initialState, type Attempt } from '#lib/study/index.js';

	const chars = Array.from(page.url.searchParams.get('c') ?? '你好们');
	const d = doneNext('h1-01', 'writing');
	const next = {
		label: d.label,
		href: d.section
			? resolve('/(app)/lesson/[id]/[section]', { id: 'h1-01', section: d.section })
			: resolve('/(app)/lesson/[id]', { id: 'h1-01' })
	};
	const store = memoryStore();
	let ledger = $state<Ledger>();
	let rows = $state<Attempt[]>([]);

	const db = 'chaiyo-dev-writing';

	let resetFailed = $state<string>();
	let resetBlocked = $state(false);

	const erase = (name: string, onBlocked: () => void) => {
		const { promise, resolve, reject } = Promise.withResolvers<void>();
		const req = indexedDB.deleteDatabase(name);
		req.onsuccess = () => resolve();
		req.onblocked = onBlocked;
		req.onerror = () => reject(req.error ?? new Error('delete failed'));
		return promise;
	};

	const readRows = () =>
		(rows = store
			.rows()
			.filter((r): r is Attempt => 'questionId' in r)
			.slice(-6));

	onMount(async () => {
		if (page.url.searchParams.has('reset')) {
			try {
				await erase(db, () => (resetBlocked = true));
				location.replace(location.pathname);
			} catch (e) {
				resetFailed = e instanceof Error ? e.message : String(e);
			}
			return;
		}
		const opened = await openLedger({
			initial: initialState({ curriculum: CURRICULUM }),
			store,
			db
		});
		await opened.sync();
		readRows();
		ledger = {
			...opened,
			record: async (input) => {
				const events = await opened.record(input);
				await opened.sync();
				readRows();
				return events;
			}
		};
	});
</script>

<!-- eslint-disable-next-line svelte/no-navigation-without-resolve -- dev-only reset needs a full reload; resolve() drops the query -->
<a href="?reset" data-sveltekit-reload class="m-4 inline-block text-label text-graphite underline"
	>reset</a
>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

{#if resetBlocked && !resetFailed}
	<p class="p-6" role="status">reset waiting: close other tabs on this page</p>
{/if}
{#if resetFailed}
	<p class="p-6" role="alert">reset failed: {resetFailed}</p>
{:else if ledger}
	<WritingRun
		{chars}
		{ledger}
		{next}
		lesson="h1-01"
		contentSha="dev-1"
		exit={resolve('/(app)/(tabs)/today')}
	/>
{/if}

<ol id="rows" class="m-4 text-label text-graphite">
	{#each rows as r (r.id)}
		<li>{r.questionId} · {String(r.correct)} · {r.answer ?? '–'}</li>
	{/each}
</ol>
