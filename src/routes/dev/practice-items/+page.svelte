<script lang="ts">
	import { onMount } from 'svelte';
	import { page } from '$app/state';
	import sprite from '#lib/assets/icons.svg?raw';
	import { catalog } from '#lib/catalog/app.js';
	import type { ImportedWord } from '#lib/content/import/sink.js';
	import { viewOf, type LessonStep } from '#lib/lesson/steps.js';
	import type { Answer, Cta } from '#lib/lesson/types.js';
	import { ngheStep } from '#lib/practice/nghe.js';
	import {
		answer,
		current,
		finished,
		itemId,
		startQueue,
		type Queue,
		type QueueItem
	} from '#lib/practice/queue.js';

	type Line = { id: string; correct: boolean | null; again: boolean };

	let words = $state<ImportedWord[]>([]);
	let queue = $state<Queue>({ items: [], at: 0 });
	let lines = $state<Line[]>([]);
	let cta = $state<Cta>();
	let failure = $state('');

	const miss = page.url.searchParams.get('miss');
	const pool = $derived(words.map((w) => w.hanzi));

	const stepOf = (item: QueueItem): LessonStep => {
		const w = words.find((x) => x.hanzi === item.word);
		if (item.skill === 'nghe')
			return ngheStep({ word: item.word, audio: w?.audio ?? '', pool, again: item.again });
		return {
			kind: 'viet',
			id: item.id,
			word: item.word,
			pinyin: w?.pinyin ?? '',
			nghia: w?.senses[0]?.vi ?? '',
			again: item.again
		};
	};

	const record = (item: QueueItem, given?: Answer) => {
		const forced = miss === item.word && !item.again;
		const correct = forced ? false : (given?.correct ?? null);
		lines = [...lines, { id: itemId(item, item.again), correct, again: item.again }];
		queue = answer(queue, correct);
	};

	onMount(() => {
		void (async () => {
			try {
				const content = await catalog.lesson('h1-01');
				words = content.words;
				queue = startQueue(
					content.words
						.slice(0, 6)
						.map((w, i) => ({ word: w.hanzi, skill: i % 2 === 0 ? 'nghe' : 'viet' }))
				);
			} catch (e) {
				failure = String(e);
			}
		})();
	});
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}

<main class="max-w-sm mx-auto p-4">
	{#if failure}
		<p data-part="failure">{failure}</p>
	{:else if queue.items.length > 0 && finished(queue)}
		<p data-part="finished">finished</p>
	{:else if queue.items.length > 0}
		{@const item = current(queue)}
		{@const step = stepOf(item)}
		{@const View = viewOf(step.kind).default}
		{#key item.id}
			<View
				{step}
				mode="feedback"
				last={queue.at === queue.items.length - 1}
				cta={(c: Cta) => (cta = c)}
				next={(a?: Answer) => record(item, a)}
			/>
		{/key}
		{#if cta}
			<button
				type="button"
				data-part="cta"
				class="mt-4 w-full rounded-action border border-ink px-4 py-3 disabled:opacity-40"
				disabled={cta.disabled}
				onclick={() => cta?.onclick()}
			>
				{cta.label}
			</button>
			{#if cta.hint}<p class="mt-2 text-label">{cta.hint}</p>{/if}
		{/if}
	{/if}

	<table class="mt-6 text-label" data-part="results">
		<thead><tr><th>id</th><th>correct</th><th>again</th></tr></thead>
		<tbody>
			{#each lines as line, i (i)}
				<tr><td>{line.id}</td><td>{String(line.correct)}</td><td>{String(line.again)}</td></tr>
			{/each}
		</tbody>
	</table>
</main>
