<script lang="ts">
	import sprite from '#lib/assets/icons.svg?raw';
	import { m } from '#lib/paraglide/messages.js';
	import AppNav from '#lib/shell/AppNav.svelte';
	import { navFor } from '#lib/shell/template.js';
	import { page } from '$app/state';
	import type { LayoutProps } from './$types';

	let { children }: LayoutProps = $props();
	const nav = $derived(navFor(page.data.shell, page.url.pathname));
	let main: HTMLElement | undefined = $state();

	function skip(event: MouseEvent) {
		event.preventDefault();
		main?.focus();
	}
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- static sprite generated by pnpm icons -->
{@html sprite}
<div class="shell" data-nav={nav?.mode}>
	<a class="skip" href="#main" onclick={skip}>{m.shell_skip()}</a>
	<AppNav {nav} />
	<main id="main" class="page-col" tabindex="-1" bind:this={main}>
		{@render children()}
	</main>
</div>
