import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { ICONS, buildSprite } from '../../../scripts/build-icons.mjs';

const read = (rel: string) => readFileSync(new URL(rel, import.meta.url), 'utf8');
const committed = read('../assets/icons.svg');
const symbols = [...committed.matchAll(/<symbol id="([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)].map(
	(m) => ({ id: m[1], body: m[2] })
);
const LINEAR = [
	'i-regular-x',
	'i-regular-caret-down',
	'i-regular-caret-right',
	'i-regular-arrow-right'
];
const SOLID = ['i-bold-check', 'i-fill-check'];
const SECOND_LAYER = 'opacity:var(--duo,.5);color:var(--duo-c,currentColor)';

describe('icon sprite generator', () => {
	it('Given_Script_When_BuildTwice_Then_BytesIdentical', () => {
		// Arrange
		// Act
		const first = buildSprite();
		const second = buildSprite();
		// Assert
		expect(second).toBe(first);
	});

	it('Given_CommittedSprite_Then_EqualsBuildSprite_SoNoHandEditSurvives', () => {
		// Arrange
		// Act
		const built = buildSprite();
		// Assert
		expect(committed).toBe(built);
	});

	it('Given_Sprite_When_ReadIds_Then_EqualsScriptListWithNoExtras', () => {
		// Arrange
		const listed = ICONS.map(([id]) => id).sort();
		// Act
		const ids = symbols.map((s) => s.id).sort();
		// Assert
		expect(ids).toEqual(listed);
		expect(ids).toHaveLength(58);
		expect(new Set(ids).size).toBe(58);
	});

	it('Given_Sprite_Then_StartsWithGeneratedComment', () => {
		// Arrange
		// Act
		const head = committed.split('\n')[0];
		// Assert
		expect(head).toBe('<!-- generated by pnpm icons — do not edit -->');
	});

	it('Given_Sprite_Then_CarriesSolarAttributionAndModificationNotice', () => {
		// Arrange
		// Act
		const second = committed.split('\n')[1];
		// Assert
		expect(second).toContain('480 Design');
		expect(second).toContain('creativecommons.org/licenses/by/4.0');
		expect(second).toContain('modified');
	});

	it('Given_Sprite_Then_RootIsHiddenFromAssistiveTech', () => {
		// Arrange
		// Act
		const root = committed.match(/<svg[^>]*>/)?.[0] ?? '';
		// Assert
		expect(root).toContain('aria-hidden="true"');
		expect(root).toContain('width="0" height="0"');
	});

	it('Given_TabIcons_Then_LineAndFillSymbolsExist', () => {
		// Arrange
		const ids = new Set(symbols.map((s) => s.id));
		// Act
		const missing = ['house', 'path', 'brain', 'user-circle'].flatMap((n) =>
			[`i-regular-${n}`, `i-fill-${n}`].filter((id) => !ids.has(id))
		);
		// Assert
		expect(missing).toEqual([]);
	});
});

describe('icon sprite duotone', () => {
	const duotone = symbols.filter((s) => !LINEAR.includes(s.id) && !SOLID.includes(s.id));

	it('Given_DuotoneSymbol_Then_SecondLayerCarriesBothVars', () => {
		// Arrange
		// Act
		const without = duotone.filter((s) => !s.body.includes(`style="${SECOND_LAYER}"`));
		// Assert
		expect(duotone.length).toBeGreaterThan(40);
		expect(without.map((s) => s.id)).toEqual([]);
	});

	it('Given_Sprite_Then_NoBareHalfOpacityLayerLeft', () => {
		// Arrange
		// Act
		const bare = symbols.filter((s) => /\sopacity="/.test(s.body));
		// Assert
		expect(bare.map((s) => s.id)).toEqual([]);
	});

	it('Given_LinearOrSolidSymbol_Then_NoDuotoneVars', () => {
		// Arrange
		const plain = symbols.filter((s) => [...LINEAR, ...SOLID].includes(s.id));
		// Act
		const tinted = plain.filter((s) => s.body.includes('--duo'));
		// Assert
		expect(plain).toHaveLength(6);
		expect(tinted).toEqual([]);
	});
});

describe('sprite mount', () => {
	const layout = read('../../routes/(app)/+layout.svelte');
	const tabBar = read('./TabBar.svelte');

	it('Given_AppLayout_Then_MountsSpriteOnceBeforeChildren', () => {
		// Arrange
		// Act
		const mounts = layout.match(/\{@html sprite\}/g) ?? [];
		// Assert
		expect(mounts).toHaveLength(1);
		expect(layout).toContain("from '#lib/assets/icons.svg?raw'");
		expect(layout.indexOf('{@html sprite}')).toBeLessThan(layout.indexOf('{@render children()}'));
	});

	it('Given_TabBar_Then_HasNoInlineSprite', () => {
		// Arrange
		// Act
		const inlines = tabBar.match(/@html|\.svg\?raw/g) ?? [];
		// Assert
		expect(inlines).toEqual([]);
		expect(tabBar).toContain('<use href="#i-regular-{tab.icon}"');
	});
});
