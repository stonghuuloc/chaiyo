export const ATTRIBUTION =
	'<!-- Solar Icon Set by 480 Design, CC BY 4.0 https://creativecommons.org/licenses/by/4.0/ — modified: secondary layer restyled to var(--duo) / var(--duo-c) -->';

const SECOND_LAYER = 'style="opacity:var(--duo,.5);color:var(--duo-c,currentColor)"';

/** @returns {string} the whole sprite, a pure function of ICONS and the Solar data */
export function buildSprite() {
	const icons = /** @type {Record<string, { body: string }>} */ (solar.icons);
	const symbols = ICONS.toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([id, name]) => {
		const icon = icons[name];
		if (!icon) throw new Error(`${id}: no Solar icon named ${name}`);
		return `<symbol id="${id}" viewBox="0 0 ${solar.width} ${solar.height}">${icon.body.replaceAll('opacity=".5"', SECOND_LAYER)}</symbol>`;
	});
	return `<!-- generated by pnpm icons — do not edit -->\n${ATTRIBUTION}\n<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">${symbols.join('')}</svg>\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const out = new URL('../src/lib/assets/icons.svg', import.meta.url);
	const sprite = buildSprite();
	writeFileSync(out, sprite);
	console.log(
		`wrote src/lib/assets/icons.svg (${Buffer.byteLength(sprite)} B, ${ICONS.length} symbols)`
	);
}
